import { describe, expect, it } from "vitest"
import { hasNoRatio } from "./precedents"

// 「인용할 판시가 없습니다」 경고의 판별기.
//
// ★이 경고는 틀리면 **살아 있는 판시를 「인용 불가」로 내린다.** 조용한 손실이라 쓰는 쪽이 원문을
//  열어 보지 않으면 안 드러난다 — 실제로 본안 파기환송 2건이 그렇게 걸렸고, 이 파일은 그 재발 탐지기다.
//
// 픽스처는 전부 **실물 응답에서 뽑은 문언**이고, 길이는 실측 구간에 맞췄다:
//   진짜 심리불속행 전문(공백 제거) 230~472  /  오탐 본안 판결 4,075·4,864
const 특례법문 =
  "이 유<br/>이 사건 상고이유에 관한 주장은 상고심절차에 관한 특례법 제4조에 해당하여 이유 없다고 인정되므로, " +
  "같은 법 제5조에 의하여 상고를 기각하기로 하여 관여 대법관의 일치된 의견으로 주문과 같이 판결한다."

// 본안 판결의 맺음말 — 일부 파기환송 + 일부 상고기각. **모든 상고기각 판결에 나오는 문장이라 신호가 아니다.**
const 본안맺음말 =
  "이 유<br/>1. 상고이유를 판단한다.<br/>4. 나. 대법원의 판단<br/>5. 결론<br/>" +
  "그러므로 원심판결 중 피고 패소 부분을 파기하고, 이 부분 사건을 다시 심리·판단하도록 원심법원에 환송하며, " +
  "원고의 상고를 기각하기로 하여, 관여 대법관의 일치된 의견으로 주문과 같이 판결한다."

const 길게 = (s: string, n: number) => s + "가".repeat(n) // 공백 없는 글자로 늘린다(공백 제거 후 길이가 는다)

describe("hasNoRatio — 심리불속행 판별", () => {
  // ★★이 줄이 `.pop()` 제거를 잰다(변이 실측 — 짐작이 아니다). 옛 코드는 전문을 「이유」로 쪼개
  //   **마지막 조각**을 재는데, 이 픽스처는 「이 유 … 상고이유 … 이유 없다」로 「이유」가 세 번 나와
  //   꼬리에 특례법 문구가 **안 남는다** ⇒ 옛 코드에서 이 줄이 red 가 된다.
  //   판례명을 일부러 무해한 것으로 둔 이유도 그것이다 — 이름 가지가 받아 주면 이 축을 못 잰다.
  it("진짜 심리불속행: 특례법 정형문 + 짧은 전문 → 경고", () => {
    expect(hasNoRatio(특례법문, "등록면허세등취소")).toBe(true)
  })

  it("판례명이 말해 주면 전문 없이도 경고", () => {
    expect(hasNoRatio(undefined, "(심리불속행) 쟁점신탁재산은 …")).toBe(true)
  })

  // ★실측 표본 622205 가 「(심리 불속행)」이었다. includes 로는 못 잡는다.
  it("판례명의 「심리 불속행」(띄어쓰기)도 잡는다", () => {
    expect(hasNoRatio(undefined, "(심리 불속행) 일반매매가 아닌 위탁매매에 해당하나 …")).toBe(true)
  })

  it("[대괄호 표기]도 잡는다", () => {
    expect(hasNoRatio(undefined, "[심리불속행 기각] 소프트웨어를 도입하여 …")).toBe(true)
  })

  // ★★오탐 재발 탐지기 — 이 둘이 이 파일의 존재 이유다.
  //   OR 에 「상고를 기각하기로 하여」를 되돌리면 여기가 red 가 된다.
  it("오탐①: 본안 파기환송(대법원 2017두31538 계열)은 경고하지 않는다", () => {
    expect(hasNoRatio(본안맺음말, "등록면허세등취소")).toBe(false)
  })

  it("오탐②: 본안 파기환송(대법원 2015두50153 계열)은 경고하지 않는다", () => {
    expect(hasNoRatio(본안맺음말, "법인세부과처분취소")).toBe(false)
  })

  // ★길이 벨트 — 특례법을 **인용만** 한 긴 본안 판결. 임계를 지우면 여기가 red 가 된다.
  it("특례법을 인용만 한 긴 본안 판결은 경고하지 않는다(전문 전체로 잰다)", () => {
    expect(hasNoRatio(길게(특례법문, 900), "법인세부과처분취소")).toBe(false)
  })

  // 위 벨트의 형제 — 「이유」가 여럿인 긴 판결. 길이 벨트 제거 변이에서 위 줄과 **함께** red 가 된다.
  //   ★처음 이 줄에 「이 줄만이 .pop() 제거를 잰다」고 적었는데 **거짓이었다**(변이 실측: M2 에서 green).
  //    `.pop()` 을 되돌리면 꼬리에 특례법이 안 남아 여전히 false 라 기대와 일치해 버린다.
  //    그 축을 실제로 재는 것은 위의 「진짜 심리불속행」 줄이다. **주석이 계기를 대신하지 못한다.**
  it("「이유」가 여러 번 나오는 긴 판결도 경고하지 않는다(꼬리가 아니라 전문 전체를 잰다)", () => {
    const 여러이유 = 길게(특례법문, 900) + "<br/>상고이유 제1점, 상고이유 제2점에 관하여 이유를 살핀다."
    expect(hasNoRatio(여러이유, "법인세부과처분취소")).toBe(false)
  })

  it("음성 대조: 정형문도 판례명 신호도 없으면 경고하지 않는다", () => {
    expect(hasNoRatio("이 유<br/>청구인의 주장은 이유 없어 모두 기각한다.", "금전무상대출 등에 따른 이익의 증여")).toBe(false)
  })

  it("전문·판례명이 없으면 경고하지 않는다(추측 금지)", () => {
    expect(hasNoRatio(undefined, undefined)).toBe(false)
    expect(hasNoRatio("", "")).toBe(false)
  })
})
