import { describe, expect, it } from "vitest"
import { hasNoRatio, reasonSection, reversalFlag } from "./precedents"

// 「인용할 판시가 없습니다」 경고와 「파기」 표시의 판별기.
//
// ★이 경고는 틀리면 **살아 있는 판시를 「인용 불가」로 내린다.** 조용한 손실이라 쓰는 쪽이 원문을
//  열어 보지 않으면 안 드러난다 — 실제로 본안 파기환송 2건이 그렇게 걸렸고, 이 파일은 그 재발 탐지기다.
//
// 픽스처는 전부 **실물 응답의 모양**이다(표제는 `【이유】`·`【주문】`, 줄바꿈은 `<br/>`).
// 실측 구간(이유 구획 · 공백 제거): 진짜 심리불속행 **129~353** ↔ 본안 판결 **1,585~4,670**.
const 특례법문 =
  "【주문】<br/>상고를 기각한다.<br/>상고비용은 원고가 부담한다.<br/>【이유】<br/><br/>" +
  "원심판결 및 상고이유서와 이 사건 기록을 모두 살펴보았으나, 상고인의 상고이유에 관한 주장은" +
  "상고심절차에 관한 특례법 제4조제1항 각 호에 정한 사유를 포함하지 아니하거나 이유가 없다고 인정되므로, " +
  "같은 법 제5조에 의하여 상고를 기각하기로 하여, 관여 대법관의 일치된 의견으로 주문과 같이 판결한다."

// 본안 판결의 맺음말 — 일부 파기환송 + 일부 상고기각. **모든 상고기각 판결에 나오는 문장이라 신호가 아니다.**
const 본안맺음말 =
  "【주문】<br/>원심판결 중 피고 패소 부분을 파기하고, 이 부분 사건을 서울고등법원에 환송한다.<br/>" +
  "원고의 상고를 기각한다.<br/>【이유】<br/>1. 상고이유를 판단한다.<br/>4. 나. 대법원의 판단<br/>5. 결론<br/>" +
  "그러므로 원심판결 중 피고 패소 부분을 파기하고, 이 부분 사건을 다시 심리·판단하도록 원심법원에 환송하며, " +
  "원고의 상고를 기각하기로 하여, 관여 대법관의 일치된 의견으로 주문과 같이 판결한다."

const 길게 = (s: string, n: number) => s + "가".repeat(n) // 공백 없는 글자로 늘린다(공백 제거 후 길이가 는다)

describe("hasNoRatio — 심리불속행 판별", () => {
  it("진짜 심리불속행: 특례법 정형문 + 짧은 이유 구획 → 경고", () => {
    expect(hasNoRatio(특례법문, "등록면허세등취소")).toBe(true)
  })

  // ★★★이 줄이 이 파일의 이유다 — 실측 표본 `2017두48505`(precSeq 421636).
  //   진짜 심리불속행인데 **전문이 10,301자**다. 이 DB가 `-----` 뒤에 **원심 본문을 통째로 덧붙이기** 때문이고,
  //   그래서 「전문 전체 길이」로 재던 판정이 이 건을 **놓쳤다**(옛 `.pop()` 판정도 놓쳤다 — 둘 다 오답이었다).
  //   ★★덧붙은 원심 본문에는 **그 판결의 `【이유】`가 또 있다** — 실측 421636은 표제가 **4개**이고
  //    구분선은 262번째(첫 이유 바로 뒤)다. 마지막 표제를 집으면 7,265번째 = 남의 판결 한복판이다.
  //    그래서 이 픽스처에 두 번째 표제를 넣는다 — 안 넣으면 「첫 표제인가 마지막 표제인가」 축이 안 재진다
  //    (실제로 안 재지고 있었다: 그 변이가 18건 전건 통과했다).
  it("덧붙은 원심 본문이 뒤에 1만 자 있어도 경고한다(-----로 자르고 **첫** 표제를 쓴다)", () => {
    const 원심본문 = "【이유】<br/>" + 길게("원심 판결 이유가 여기부터 이어진다.", 10000)
    const 실물모양 = 특례법문 + "<br/>-----------------<br/>" + 원심본문
    expect(hasNoRatio(실물모양, "종전 본점을 유지하면서 더 큰 영업점으로 이전해도 본점이전인지")).toBe(true)
  })

  //   ★적힌 상한: **구분선이 없으면서 표제가 둘인 판**은 이 계기가 못 가른다 — 첫 표제를 쓰면 뒤엣것까지
  //    딸려와 길어지고, 마지막을 쓰면 특례법이 안 잡혀서 **어느 쪽이든 false**다(그래서 그 축의 단언을 안 만들었다.
  //    만들면 변이가 안 걸리는 「초록인데 안 재는」 줄이 된다). 표본 13건에는 그 모양이 없다
  //    — 실측: 표제 4개짜리(421636)엔 구분선이 있고, 구분선 없는 것(204350·622075)은 표제가 1개다.

  it("판례명이 말해 주면 전문 없이도 경고", () => {
    expect(hasNoRatio(undefined, "(심리불속행) 쟁점신탁재산은 …")).toBe(true)
  })

  // ★실측 표본 622205 가 「(심리 불속행)」이었다. includes 로는 못 잡는다.
  it("판례명의 「심리 불속행」(띄어쓰기)도 잡는다", () => {
    expect(hasNoRatio(undefined, "(심리 불속행) 일반매매가 아닌 위탁매매에 해당하나 …")).toBe(true)
  })

  it("[대괄호 표기]도 잡는다", () => {
    expect(hasNoRatio(undefined, "[심리불속행 기각] 소프트웨어를 도입하여 …")).toBe(true)
  })

  // ★★오탐 재발 탐지기 — OR 에 「상고를 기각하기로 하여」를 되돌리면 여기가 red 가 된다.
  it("오탐①: 본안 파기환송(대법원 2017두31538 계열)은 경고하지 않는다", () => {
    expect(hasNoRatio(본안맺음말, "등록면허세등취소")).toBe(false)
  })

  it("오탐②: 본안 파기환송(대법원 2015두50153 계열)은 경고하지 않는다", () => {
    expect(hasNoRatio(본안맺음말, "법인세부과처분취소")).toBe(false)
  })

  it("특례법을 인용만 한 긴 본안 판결은 경고하지 않는다(길이 벨트)", () => {
    expect(hasNoRatio(길게(특례법문, 900), "법인세부과처분취소")).toBe(false)
  })

  // ★`.pop()` 복원 변이를 잡는 줄 — 「이유」가 본문에 여러 번 나와 꼬리에 특례법이 안 남는다.
  it("「이유」가 여러 번 나와도 첫 표제 이후를 잰다(꼬리가 아니다)", () => {
    expect(hasNoRatio(특례법문 + "<br/>상고이유 제1점에 관하여 이유를 살핀다.", "무해한이름")).toBe(true)
  })

  it("음성 대조: 정형문도 판례명 신호도 없으면 경고하지 않는다", () => {
    expect(hasNoRatio("【이유】<br/>청구인의 주장은 이유 없어 모두 기각한다.", "금전무상대출 등에 따른 이익의 증여")).toBe(false)
  })

  // ★표제를 못 찾으면 **판정하지 않는다**(경고는 인용을 막으므로 추측 금지). 그 계약을 못 박는다.
  it("이유 표제를 못 찾으면 경고하지 않는다", () => {
    expect(reasonSection("표제가 없는 글. 상고심절차에 관한 특례법 제4조.")).toBe(null)
    expect(hasNoRatio("표제가 없는 글. 상고심절차에 관한 특례법 제4조.", "무해한이름")).toBe(false)
  })

  it("전문·판례명이 없으면 경고하지 않는다(추측 금지)", () => {
    expect(hasNoRatio(undefined, undefined)).toBe(false)
    expect(hasNoRatio("", "")).toBe(false)
  })
})

describe("reversalFlag — 파기 표시(카드 요청 ②)", () => {
  it("주문에 파기+환송이 있으면 파기환송", () => {
    const r = reversalFlag(본안맺음말)
    expect(r.reversed).toBe(true)
    expect(r.remanded).toBe(true)
    expect(r.text).toContain("파기")
  })

  // ★실측 표본 `2012두6551`(precSeq 164541)의 주문 문언 그대로.
  it("전부 파기환송 주문도 잡는다", () => {
    const r = reversalFlag("【주문】<br/>원심판결을 파기하고, 사건을 서울고등법원에 환송한다.<br/>【이유】<br/>상고이유를 판단한다.")
    expect(r.reversed).toBe(true)
    expect(r.remanded).toBe(true)
  })

  it("파기하되 환송이 없으면 자판으로 가른다", () => {
    const r = reversalFlag("【주문】<br/>원심판결을 파기한다. 제1심판결을 취소한다.<br/>【이유】<br/>…")
    expect(r.reversed).toBe(true)
    expect(r.remanded).toBe(false)
  })

  // ★음성 대조 — 심리불속행(상고기각)은 파기가 아니다. 두 표시가 같이 붙으면 독자가 헷갈린다.
  it("음성: 상고기각 주문에는 안 붙는다", () => {
    expect(reversalFlag(특례법문).reversed).toBe(false)
  })

  // ★★이유 본문의 「파기」에 반응하면 안 된다 — 주문 구획만 본다.
  //   본안 판결은 인용 판례를 논하며 「…파기환송한 바 있다」를 이유에 쓴다.
  it("음성: 이유 본문에만 「파기」가 있으면 안 붙는다(주문 구획만 잰다)", () => {
    const 이유에만 = "【주문】<br/>상고를 기각한다.<br/>【이유】<br/>선례는 원심판결을 파기하고 환송한 바 있으나 이 사건은 다르다."
    expect(reversalFlag(이유에만).reversed).toBe(false)
  })

  it("주문 표제가 없으면 판정하지 않는다", () => {
    expect(reversalFlag("표제 없는 글에 파기와 환송이라는 낱말만 있다").reversed).toBe(false)
    expect(reversalFlag(undefined).reversed).toBe(false)
  })
})
